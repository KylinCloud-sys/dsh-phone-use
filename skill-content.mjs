export const SKILL_CONTENT = `# 手机操控（dsh-phone-use）

> 工具名可能是 phone_info 或 mcp__phone__phone_info（取决于挂载方式），按实际可用名调用。

在**后台**操控手机：看不见手机、不抢焦点、不动鼠标，也能截图、点击、滑动、输入。

当前只实现了「小米互联」一条通道，具体见文末 **通道：小米互联**。adb 与其他品牌规划中。

## 硬规则（优先级最高，任何时候不得违反）

1. **只用当前通道，不要自己换**。当前是小米互联，不要改用 adb；确实需要时**先问用户**，并且**先问是哪一台设备**（可能同时连了多台），不得自行决定。
2. **全后台**。点击/滑动/输入全部走后台消息；不把窗口提到前台、不移动鼠标、不抢焦点。只有"后台点击真的失败"或"窗口最小化导致做不完"这两种情况例外（见下）。
3. **未经用户明确许可，绝不自行动手**：下单/支付/确认购买、发送消息、删除、卸载、改系统设置、退出登录、授权类弹窗。遇到这类页面**只报告在哪、等用户确认**，不许自己点。拿不准某个按钮有没有副作用时，同样先问。
4. **可能与你冲突的操作，必须先说明并得到同意**：
   - 全局键盘注入（按下真实 Ctrl 等）——默认**禁用**，只有用户同意后才用；
   - 把窗口提到前台、用 SendInput 真实点击；
   - 任何会覆盖用户剪贴板内容的长期占用（插件会临时写入并立即还原，这属于已授权的默认行为）。
5. **失败即停**。后台点击连续两次"该有变化却没变化"→ 停下来报告，说清已做/未做/卡在哪，**不许自动转前台、不许盲目重试**。
6. 开始任何手机操作前先调用 \`phone_wake\`。它会后台唤起并等待画面；成功或超时都要先处理返回里的 \`unlockRequired\` / \`userPrompt\`。**只要 \`unlockRequired=true\`，必须明确提醒主人在手机上手动完成指纹解锁，并等待主人确认"已解锁"后才能调用 \`phone_see\`/\`phone_do\`；绝不代点锁屏、授权或配对按钮。**

## 坐标

- 所有坐标都是**画面区百分比**（0-100），格式 "x,y"。
- 画面区 = 窗口里那块没有边框的手机画面（标定 GUI 返回的那个尺寸），窗口移动/缩放/换分辨率都不影响百分比。
- \`phone_info\` 返回 \`s:[宽,高]\`，那就是画面区像素尺寸，仅用于换算参考，不用它算点击。

## 工具

### phone_wake
全后台唤起并等待真实手机画面。**不点任务栏/托盘、不 SendInput、不动鼠标、不抢焦点。**

先看 \`state\`，再决定下一步：

| \`state\` | 含义 | 你该做什么 |
|---|---|---|
| \`ready\` / \`restored\` / \`started\` | 拿到真实画面（手机已解锁） | \`unlockRequired:false\`，可直接 \`phone_see\`/\`phone_do\` |
| \`awaiting-unlock\` | 已连上，但手机锁屏 | \`unlockRequired:true\`，**请主人手动指纹解锁并等确认**；插件绝不代点锁屏/授权/配对 |
| \`connect-failed\` | 投屏连不上 | 让主人确认同局域网、手机端互联已开启，重新发起投屏；**不需要解锁** |
| \`screen-not-projected\` | 窗口在但画面空白 | 多半不在同一局域网；检查网络，**不需要解锁** |
| \`phone-not-found\` | 连窗口都没有 | 设备不在身边或不在同一局域网 |
| \`client-not-found\` / \`launch-failed\` | 客户端缺失或启动失败 | 请主人安装/手动打开一次 |

附加字段：
- \`ocrAvailable\` / \`ocrHint\`：\`false\` 表示没装简体中文 OCR 语言包，页面状态判断会退化；\`ocrHint\` 里有安装指引，可转告主人。
- \`aspect\`：画面宽高比（已做横竖屏归一化），仅用于排查，不用来判断状态。

### phone_info
体检：窗口在不在、画面区多大、是否最小化、前后台。约 60 tokens，**只在开头或怀疑出问题时调**。

### phone_see
看当前画面。
- \`image\`：\`auto\`（默认）/ \`full\` / \`none\`
- \`region\`："x,y,w,h" 百分比，只看一块（翻列表、看输入框周围时用）
- 没变化时返回 \`{"ok":true,"ch":false}\`，**不带图**，几乎不花 token
- 画面空白（投屏没建立）返回 \`{"blank":true,"state":"screen-not-projected"}\`，同样**不带图**；这时该提醒主人检查是否同一局域网，而不是等指纹解锁

### phone_panel
打开系统面板（后台手势）。**不用自己算坐标，也不用自己拼滑动。**

- \`side:"control"\`（默认）→ 控制中心：快捷开关、亮度、音量、Wi-Fi/蓝牙/移动数据
- \`side:"notification"\` → 通知栏：消息通知列表

面板已打开时再调会**先返回再重新拉**，不会叠在一起。

**两个面板之间不能横向滑动切换**（投屏的鼠标消息模拟做不到，横滑会被系统识别成返回手势或纵向拖动）。想从通知栏去控制中心，就 \`phone_back\` 关掉再 \`phone_panel side:"control"\` 重新拉，效果一样。

### phone_back
执行系统返回手势（从右边缘往左滑，后台）。

- 关闭通知栏 / 控制中心
- App 内返回上一页
- 相当于按手机的返回键

**关闭面板一律用它**，不要自己拼滑动路径。

### phone_do
一次执行多步，**这是省 token 的主力**。
\`\`\`json
[
  {"tap":"50,88"},
  {"swipe":"50,95>50,40","ms":300},
  {"longpress":"40,96"},
  {"text":"你好","at":"40,96"},
  {"key":"backspace","n":3},
  {"panel":"control"},
  {"back":true},
  {"wait":600}
]
\`\`\`
- \`tap\` / \`longpress\` / \`swipe\`：百分比
- \`key\`：\`backspace|enter|esc|tab|delete|space\`，\`n\` 为次数（默认 1，按需给，不要固定 3）
- \`text\`：输入文字，具体用法见通道章节
- \`clip\`：\`"read"\` 读本机剪贴板（手机刚复制过来的内容），给字符串则写入；\`"@restore"\` 还原写入前的备份
- \`panel\`：\`"control"\` 开控制中心 / \`"notification"\` 开通知栏（不用给坐标）
- \`back\`：\`true\` 执行返回手势（关闭面板、App 内返回）
- \`wait\`：毫秒

执行完自动截一张图并按变化量决定回什么图。

## 省 token 的节奏（照这个做）

1. 开头 \`phone_info\` 一次即可，之后不要反复调。
2. \`phone_do\` 一次塞 2-5 步，**不要每点一下就看一次**。
3. 只有在"需要判断下一步点哪"时才 \`phone_see\`；同一画面不要连看两次。
4. 看细节用 \`region\`（例如只看输入框那条），别整屏重发。
5. 长文本（聊天记录、列表）优先 \`clip:"read"\`，而不是截图。

## 安全与隐私

- 剪贴板会被临时占用并在完成后还原；**不要把密钥、密码等敏感内容当测试文本**粘贴到手机上。
- 每次动作都会留下执行回执（点了哪、有没有变化），可以据此向用户解释做了什么。
- 未经许可不得发送任何消息；\`发送\`/\`转账\`/\`确认\` 类按钮一律先问。

## 点击验证（重要，用它代替"我以为点到了"）

给 \`phone_do\` 传 \`verify:"x,y,w,h"\`（要变化的那块区域百分比），执行后会返回：

- \`hit:true\` 这块真的变了 → 点到了
- \`hit:false\` + \`tries:2\` 自动重试过一次仍没变 → **这次点击没生效**，别再假设成功
- \`banner:true\` 顶部条带变了 → 多半弹了通知、页面被挤下去，此时 hit 不可信，重新 \`phone_see\` 再定位

惯例：点「下一题 / 发送 / 切换标签」这类**应该引起画面变化**的按钮时，都带上 verify。

## 权限三档（由 profile 配置决定，你左右不了也不该试探）

| 档 | 行为 |
|---|---|
| \`full\` | 不拦 |
| \`auto\` | 标了 \`danger:true\` 或落在危险区域（如提交/支付按钮）的步骤要确认 |
| \`ask\` | 任何写操作都要确认 |

被拦时返回 \`{"ok":false,"need":"confirm","reason":...}\`：**这时必须停下来向用户说明并取得同意**，然后带 \`confirm:true\` 重调。不要自己猜、不要绕过、不要把 confirm 当默认参数。

判断某一步有没有副作用时，宁可标 \`danger:true\` 让用户点头，也不要默默执行。

## 已知限制

- **OCR 不是通用读屏**：插件只用它判断页面状态（连接中 / 待解锁 / 连接失败），普通正文（聊天记录、列表、小字）识别不准，读内容以看图为主。
- **画面会被通知横幅挤位**：坐标稳定但内容可能移位，点了之后拿不准就用 \`verify\` 判断。
- **单窗口单手机**：没有多设备支持。

## 通道：小米互联

当前唯一实现的通道，靠「跨屏协作 / 妙享桌面」窗口操控手机。

### 输入文字

- **英文/数字/符号**：\`{"text":"hello123"}\`，逐键输入，不动剪贴板、无冲突。
- **中文**：三步走，**不要**用 \`text\` 直接塞，也不要猜菜单位置。

  **⚠ 输入前必须先确认输入框是空的**（硬性前置，不是可选项）。输入框里只要有内容，长按就会**选中文字**，此时弹出的通常是「全选 / 剪切 / 复制」这类**文字选中菜单**，里面**没有「粘贴」**，结果就是根本粘不上、旧内容还留着。

  > 各家 ROM 的菜单文案不同（小米、华为、OPPO、vivo、三星都不一样），所以**不要按名字认菜单**，只认「有没有粘贴项」这个事实：有粘贴 = 空输入框，可以点；只有全选/剪切/复制 = 有内容被选中，必须先清空。
  - 怎么确认：先 \`phone_see\` 看一眼输入框（用 \`region\` 只看那一条，省 token）。
  - 有内容就先清空：\`{"tap":"输入框坐标"}\` 定位光标，再 \`{"key":"backspace","n":<够长的次数>}\`。清完再截图确认只剩占位符，然后才 \`openmenu\`。
  - **清空必须由你判断**：只有你能看到输入框里有没有东西。插件不会替你自动清（容易误删用户已输入的内容）。
  1. \`{"openmenu":"40,96","text":"要输入的话"}\` → 返回菜单裁剪图（\`crop\`）+ 换算元数据 \`box\`（\`x/y/w/h/scale/screen\`）。**这一步不会点任何菜单项。**
  2. 看那张图，找到「粘贴」，算出百分比：\`(图上像素 / scale + box.x) / box.screen.w * 100\`、\`(图上像素 / scale + box.y) / box.screen.h * 100\`，然后 \`{"tap":"x,y"}\` 点一次。
  3. 截图确认字进去了；最后 \`{"clip":"@restore"}\` 还原用户剪贴板。
- 菜单里没有「粘贴」时，先分清两种原因：**① 输入框有内容**（弹的是选中菜单，只有全选/剪切/复制）→ 先清空再重来；**② 剪贴板还没同步到手机**（菜单只有输入法自带项）→ 加长等待重试一次。两者都排除后仍没有，就如实报告，**不要**点菜单里的其他项凑数。
- 菜单项因**设备厂商、输入法、App、页面**而异，文案和排列都不固定（可能带输入法自带功能、AI 写作、常用语、表情、⋮ 更多等）。所以永远**看图找「粘贴」两个字**再点，不存在通用坐标，也不要按位置猜。
- 菜单坐标不写死。只有在自动定位失灵（个别 App 的菜单抓不到）时才传 \`menu:"x,y"\` 手动指定。
- **不要**自己用全局 Ctrl 注入（会和用户的物理键盘冲突）。

### 不要手动清理小米互联进程

「妙享桌面」是常驻程序，通常一直最小化在任务栏。它被 kill 后无法用普通方式拉起，只能让主人手动恢复，而缺了它投屏永远连不上。

确实需要重置时，**只针对「跨屏协作」**，绝不碰妙享桌面。`
